"""Exact reproducible source-integrity acceptance test on the imported distribution."""
import shutil
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
from verify_source_integrity import check_source


class ImportedV21152Tests(unittest.TestCase):
    def test_original_zip_and_complete_engine_are_identical(self):
        result = check_source(ROOT)
        self.assertEqual(result["status"], "source_integrity_passed")
        self.assertEqual(result["manifest_file_hashes_verified"], 651)
        self.assertEqual(result["extracted_files_compared"], 652)
        self.assertEqual(result["original_zip_sha256"],
                         "9369656f0216cebb6dccce0d0155bffa16d8c384da6a984bf848cdd8aa003c54")
        self.assertFalse(result["complete_runtime_tests"])
        self.assertFalse(result["physical_cricut_verified"])
        self.assertFalse(result["gpu_inference_verified"])


    def test_generated_bytecode_does_not_mask_unexpected_sources(self):
        """Compile caches are ignored; any unlisted source still fails closed."""
        with tempfile.TemporaryDirectory(prefix="smartsvg-inventory-") as td:
            isolated = Path(td)
            shutil.copytree(
                ROOT / "engine",
                isolated / "engine",
                ignore=shutil.ignore_patterns("__pycache__", "*.pyc", "*.pyo"),
            )
            archive_dir = isolated / "source-releases"
            archive_dir.mkdir()
            shutil.copy2(
                ROOT / "source-releases" / "ComfyUI_SmartSVG_Studio_V21_15_2_Installation.zip",
                archive_dir,
            )
            cache = isolated / "engine" / "smartsvg_ai" / "__pycache__"
            cache.mkdir(exist_ok=True)
            (cache / "probe.cpython-311.pyc").write_bytes(b"synthetic generated bytecode")
            self.assertEqual(check_source(isolated)["status"], "source_integrity_passed")

            # Never ignore a rogue Python file merely because it is in a cache folder.
            (cache / "unexpected.py").write_text("print('unexpected')\n")
            with self.assertRaisesRegex(ValueError, "SOURCE_FILE_INVENTORY_MISMATCH"):
                check_source(isolated)
            (cache / "unexpected.py").unlink()

            # Bytecode outside the standard generated cache path is also unexpected.
            (isolated / "engine" / "unexpected.pyc").write_bytes(b"not generated here")
            with self.assertRaisesRegex(ValueError, "SOURCE_FILE_INVENTORY_MISMATCH"):
                check_source(isolated)


if __name__ == "__main__":
    unittest.main()
