"""SmartSVG V21.15.1, read-only offline QA for Cricut PNG/SVG exports.

This does not certify Design Space import or a physical cut.
This module works on outputs generated by SmartSVG, never alters them, and
is independent of optional local AI or the ComfyUI frontend.
"""
from __future__ import annotations
import json, math, re
from pathlib import Path
from typing import Any
import cv2
import numpy as np
from PIL import Image
import xml.etree.ElementTree as ET

MAX_REPORT_BYTES=12_000_000
MAX_ART_BYTES=40_000_000
MAX_IMAGE_PIXELS=35_000_000
MAX_OBJECTS=1000
COVERAGE_RECTANGLE=0.96
ALPHA_LIMIT=20

class QAError(ValueError): pass

def _safe_file(root: Path, name: str, limit: int=MAX_ART_BYTES) -> Path:
    if not isinstance(name,str) or not name.strip():raise QAError('chemin manquant')
    root=root.resolve()
    candidate=Path(name)
    candidate=(candidate if candidate.is_absolute() else root/candidate).resolve()
    if not candidate.is_relative_to(root):raise QAError('chemin externe au projet refuse')
    if not candidate.is_file() or candidate.stat().st_size>limit:raise QAError('fichier absent ou trop grand')
    return candidate

def _geom(path: Path)->dict:
    with Image.open(path) as im:
        if im.width*im.height>MAX_IMAGE_PIXELS:raise QAError('image trop grande')
        if im.mode not in ('RGBA','LA','P') and 'transparency' not in im.info:
            a=np.full((im.height,im.width),255,np.uint8)
        else:a=np.asarray(im.convert('RGBA').getchannel('A'),np.uint8)
    levels={}
    for threshold in (0,ALPHA_LIMIT,128):
        n, _, stats, _=cv2.connectedComponentsWithStats((a>threshold).astype('uint8'),8)
        levels[str(threshold)]={'count':int(n-1),'significant':int(sum(s[-1]>=100 for s in stats[1:]))}
    main=a>128
    cs,_=cv2.findContours(main.astype('uint8'),cv2.RETR_EXTERNAL,cv2.CHAIN_APPROX_SIMPLE)
    if not cs:
        return {'image_size_px':[a.shape[1],a.shape[0]],'alpha_components':levels,'empty':True,'near_rectangle':False}
    c=max(cs,key=cv2.contourArea)
    x,y,w,h=cv2.boundingRect(c)
    ratio=float(cv2.contourArea(c)/max(1,w*h))
    perimeter=cv2.arcLength(c,True)
    vertices=int(len(cv2.approxPolyDP(c,max(1,perimeter*.025),True)))
    return {'image_size_px':[a.shape[1],a.shape[0]],'alpha_components':levels,
            'alpha_nonzero_fraction':round(float(np.mean(a>0)),5),
            'alpha_main_fraction':round(float(np.mean(main)),5),
            'main_rect_fill_ratio':round(ratio,5), 'approx_vertices':vertices,
            'near_rectangle':bool(ratio>=COVERAGE_RECTANGLE and vertices<=5),'empty':False}

def _svg_geom(path:Path)->dict:
    payload=path.read_bytes()
    if any(tag in payload.lower() for tag in (b'<!doctype',b'<!entity',b'<script',b'<image',b'xlink:href',b'<foreignobject')):
        raise QAError('contenu SVG actif / lie refuse')
    try: root=ET.fromstring(payload)
    except ET.ParseError as e:raise QAError('SVG XML invalide') from e
    if not root.tag.endswith('svg'):raise QAError('racine non SVG')
    paths=[x for x in root.iter() if x.tag.rsplit('}',1)[-1]=='path']
    length=root.get('width','')
    mm=re.fullmatch(r'\s*(\d+(?:\.\d+)?)\s*mm\s*',length)
    return {'path_elements':len(paths),'width_mm':float(mm.group(1)) if mm else None,
            'embedded_raster':False,'svg_parse_ok':True}

def audit_project(report_path: str | Path, *, requested_intent: str='sticker_contour')->dict[str,Any]:
    report_path=Path(report_path).resolve()
    if not report_path.is_file() or report_path.stat().st_size>MAX_REPORT_BYTES:raise QAError('rapport absent ou surdimensionne')
    project=report_path.parent
    report=json.loads(report_path.read_text(encoding='utf-8'))
    if not isinstance(report,dict):raise QAError('rapport malforme')
    objects=report.get('objets',[])
    if not isinstance(objects,list) or len(objects)>MAX_OBJECTS:raise QAError('trop d objets')
    results=[];critical=[];warnings=[]
    for i,obj in enumerate(objects,1):
        if not isinstance(obj,dict):raise QAError('objet non conforme')
        png=obj.get('fichier_png_cricut') or obj.get('png')
        svg=obj.get('fichier_svg_contour') or obj.get('svg_contour')
        if not png:results.append({'index':i,'blocked':['PNG_MANQUANT']});critical.append('PNG_MANQUANT');continue
        try:
            m=_geom(_safe_file(project,png))
            s=_svg_geom(_safe_file(project,svg)) if svg else None
        except (QAError, OSError, ValueError) as e:
            results.append({'index':i,'blocked':['FICHIER_NON_VERIFIABLE'],'reason':str(e)})
            critical.append('FICHIER_NON_VERIFIABLE');continue
        block=[];warn=[]
        if m['empty']:block.append('ALPHA_VIDE')
        if requested_intent=='sticker_contour':
            if obj.get('type_coupe')=='CADRE_RECTANGULAIRE' or m['near_rectangle']:
                block.append('SILHOUETTE_RECTANGULAIRE_NON_FIABLE')
        if s is None: block.append('SVG_MANQUANT')
        elif s['path_elements']==0 or (obj.get('contour_nombre_chemins') is not None and obj['contour_nombre_chemins']!=s['path_elements']):
            block.append('SVG_CHEMINS_INCOHERENTS')
        elif s['width_mm'] is not None and obj.get('largeur_finale_avec_marge_mm') is not None:
            if abs(s['width_mm']-float(obj['largeur_finale_avec_marge_mm']))>.15: block.append('DIMENSIONS_MM_INCOHERENTES')
        if m['alpha_components']['0']['count']>m['alpha_components'][str(ALPHA_LIMIT)]['count']:
            warn.append('ALPHA_FAIBLE_FRAGMENTE')
        if obj.get('facteur_interpolation',1)>1.5:
            warn.append('AGRANDISSEMENT_INTERPOLATION')
        for c in block:critical.append(c)
        for w in warn:warnings.append(w)
        results.append({'index':i,'geometry':m,'svg':s,'blocked':block,'warnings':warn})
    pages=[]
    for j,page in enumerate(report.get('planches_cricut') or report.get('planches') or [],1):
        expected=int(page.get('objets',len(page.get('elements_source',[]))))
        filename=page.get('fichier')
        if not filename:continue
        try:g=_geom(_safe_file(project,filename))
        except QAError as e:
            critical.append('PLANCHE_NON_VERIFIABLE');pages.append({'index':j,'error':str(e)});continue
        n=g['alpha_components'][str(ALPHA_LIMIT)]['count']
        b=[];w=[]
        if n!=expected:b.append('NOMBRE_ILOTS_ALPHAS_20_INCOHERENT')
        if g['alpha_components']['0']['count']>expected:w.append('FRAGMENTS_ALPHA_FAIBLES_DANS_PLANCHE')
        critical.extend(b);warnings.extend(w)
        pages.append({'index':j,'expected':expected,'geometry':g,'blocked':b,'warnings':w})
    if not objects:critical.append('AUCUN_OBJET')
    status='BLOCKED' if critical else 'REVIEW_REQUIRED'
    return {'schema_version':'real-artifact-qa-1', 'source_report':str(report_path),
            'requested_intent':requested_intent,'status':status,'objects_tested':len(objects),
            'pages_tested':len(pages),'blocking_codes':sorted(set(critical)),
            'warning_codes':sorted(set(warnings)), 'objects':results,'pages':pages,
            'external_validation':{'design_space_import':'NOT_TESTED','physical_cut':'NOT_TESTED',
                                   'human_quality_review':'NOT_TESTED','gpu_ai':'NOT_TESTED'},
            'scope':'STATIC_RASTER_AND_SVG_EXPORT_QA_NOT_CRICUT_CERTIFICATION'}
